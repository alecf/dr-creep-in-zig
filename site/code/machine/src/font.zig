/// The ROM image, indexed by character code.
pub const rom: [256][8]u8 = build: {
    @setEvalBranchQuota(20_000);
    var out: [256][8]u8 = @splat(@splat(0));
    var defined: [256]bool = @splat(false);
    for (art) |entry| {
        const code, const rows = entry;
        if (defined[code]) @compileError(std.fmt.comptimePrint("glyph 0x{X:0>2} drawn twice", .{code}));
        defined[code] = true;
        for (rows, 0..) |row, y| {
            var byte: u8 = 0;
            for (row, 0..) |ch, x| {
                switch (ch) {
                    '#' => byte |= 0x80 >> x,
                    '.' => {},
                    else => @compileError("font art uses only '#' and '.'"),
                }
            }
            out[code][y] = byte;
        }
    }
    // Lowercase slots borrow the capitals.
    for ('a'..'z' + 1) |c| out[c] = out[c - 0x20];
    break :build out;
};

test "font basics" {
    try std.testing.expectEqual(@as(u8, 0), rom[' '][3]);
    try std.testing.expectEqual(rom['A'], rom['a']);
    try std.testing.expectEqual(@as(u8, 0b1111_1110), rom['L'][6]);
    // Every printable code has a glyph (space aside).
    for (0x21..0x60) |c| {
        var lit: u32 = 0;
        for (rom[c]) |b| lit += @popCount(b);
        try std.testing.expect(lit > 0);
    }
}
